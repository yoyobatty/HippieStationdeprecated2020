"""Generates micro.dm: stand-alone BYOND probe of what makes a proc call or a var read cost more.
python gen_micro.py && dm micro.dm && dd micro.dmb -invisible -trusted
Results in world.log: "case | ns per op (min of TRIES) | median", baseline (empty loop) already subtracted.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N_BIG = 1500  # procs / vars on the "big" types, like /atom in Hippie

out = []
w = out.append
w("""// GENERATED by gen_micro.py, do not edit
#define REPS 200000
#define TRIES 9

/world
	fps = 10
	maxx = 10
	maxy = 10
	maxz = 1
	loop_checks = 0

var/global/gnum = 1
var/global/list/glist = list(1, 2, 3)

/datum/controller/global_vars
/datum/controller/global_vars/var/global/static_num = 1
var/datum/controller/global_vars/GLOB = new

/datum/small
	var/a = 1
	var/b = 2
	var/c = 3
	var/list/l = null

/datum/small/proc/p0()
	return 1
/datum/small/proc/p3(x, y, z)
	return x
/datum/small/proc/p3d(x = 1, y = 2, z = 3)
	return x
/datum/small/proc/locals10()
	var/a1 = 1
	var/a2
	var/a3
	var/a4
	var/a5
	var/a6
	var/a7
	var/a8
	var/a9
	var/a10
	return a1
/datum/small/proc/nowait()
	set waitfor = FALSE
	return 1
/datum/small/proc/three_reads()
	return a + a + a
/datum/small/proc/three_reads_local()
	var/x = a
	return x + x + x
/datum/small/proc/src_reads()
	return src.a + src.b + src.c

/proc/g0()
	return 1
/proc/g1(d)
	return d

// override chain: chain5 overrides p0 five times, each calling ..()
/datum/small/chain1/p0()
	return ..()
/datum/small/chain1/chain2/p0()
	return ..()
/datum/small/chain1/chain2/chain3/p0()
	return ..()
/datum/small/chain1/chain2/chain3/chain4/p0()
	return ..()
/datum/small/chain1/chain2/chain3/chain4/chain5/p0()
	return ..()

// deep type, proc only on the root
/datum/small/d1/d2/d3/d4/d5/d6/d7/d8/d9/d10/d11/d12/d13/d14/d15/d16/d17/d18/d19/d20

/datum/small/init_list
	var/list/il = list()
""")

# big type: many vars and procs
w("/datum/big")
for i in range(N_BIG):
    w(f"\tvar/v{i} = {i}")
for i in range(N_BIG):
    w(f"/datum/big/proc/bp{i}()\n\treturn {i}")
w("/datum/big/proc/p0()\n\treturn 1")
w("/datum/big/proc/three_reads()\n\treturn v700 + v700 + v700")
# datum with many vars overridden at runtime
w("/datum/big/proc/override_all()")
for i in range(0, N_BIG, 1):
    w(f"\tv{i} = {i + 1}")

w("""
var/list/case_names = list()
var/list/results = list()

/proc/now_ms()
	return world.tick_usage * world.tick_lag * 100 / 1000 * 10

/proc/run_case(id, reps, datum/small/S, datum/big/B, datum/big/BO, datum/small/C5, datum/small/D20, list/L100, list/O100)
	var/dummy = 0
	var/t0 = world.tick_usage
	switch(id)
		if(1) // baseline
			for(var/i in 1 to reps)
				dummy = i
		if(2)
			for(var/i in 1 to reps)
				dummy = g0()
		if(3)
			for(var/i in 1 to reps)
				dummy = g1(S)
		if(4)
			for(var/i in 1 to reps)
				dummy = S.p0()
		if(5)
			for(var/i in 1 to reps)
				dummy = S.p3(i, i, i)
		if(6)
			for(var/i in 1 to reps)
				dummy = S.p3(x = i, y = i, z = i)
		if(7)
			for(var/i in 1 to reps)
				dummy = S.p3d()
		if(8)
			for(var/i in 1 to reps)
				dummy = S.locals10()
		if(9)
			for(var/i in 1 to reps)
				dummy = S.nowait()
		if(10)
			for(var/i in 1 to reps)
				dummy = C5.p0()
		if(11)
			for(var/i in 1 to reps)
				dummy = D20.p0()
		if(12)
			for(var/i in 1 to reps)
				dummy = B.p0()
		if(13)
			for(var/i in 1 to reps)
				dummy = S.a
		if(14)
			for(var/i in 1 to reps)
				dummy = B.v700
		if(15)
			for(var/i in 1 to reps)
				dummy = BO.v700
		if(16)
			for(var/i in 1 to reps)
				dummy = gnum
		if(17)
			for(var/i in 1 to reps)
				dummy = GLOB.static_num
		if(18)
			for(var/i in 1 to reps)
				dummy = S.three_reads()
		if(19)
			for(var/i in 1 to reps)
				dummy = S.three_reads_local()
		if(20)
			for(var/i in 1 to reps / 100)
				for(var/datum/small/x in L100)
					dummy = x
		if(21)
			for(var/i in 1 to reps / 100)
				for(var/datum/small/x as anything in L100)
					dummy = x
		if(22)
			for(var/i in 1 to reps)
				dummy = L100.len
		if(23)
			for(var/i in 1 to reps)
				dummy = length(L100)
		if(24)
			for(var/i in 1 to reps)
				dummy = world.time
		if(25)
			for(var/i in 1 to reps)
				dummy = world.tick_usage
		if(26)
			for(var/i in 1 to reps / 10)
				var/datum/small/x = new
				dummy = x
		if(27)
			for(var/i in 1 to reps / 10)
				var/datum/small/init_list/x = new
				dummy = x
		if(28)
			for(var/i in 1 to reps)
				dummy = istype(S, /datum/small)
		if(29)
			for(var/i in 1 to reps)
				dummy = S.vars["a"]
		if(30)
			for(var/i in 1 to reps)
				dummy = BO.three_reads()
		if(31)
			for(var/i in 1 to reps)
				dummy = (S.l && S.l[1])
		if(32)
			for(var/i in 1 to reps)
				dummy = S.src_reads()
		if(33)
			for(var/i in 1 to reps / 100)
				for(var/x in O100)
					dummy = x
		if(34)
			for(var/i in 1 to reps / 100)
				for(var/j in 1 to O100.len)
					dummy = O100[j]
		if(35)
			for(var/i in 1 to reps)
				dummy = S?.a
		if(36)
			for(var/i in 1 to reps)
				dummy = isnull(S)
		if(37)
			for(var/i in 1 to reps)
				dummy = S == null
		if(38)
			for(var/i in 1 to reps)
				dummy = BO.bp1400()
		if(39)
			for(var/i in 1 to reps)
				dummy = BO.bp3()
		if(40)
			for(var/i in 1 to reps)
				dummy = B.v3
		if(41)
			for(var/i in 1 to reps)
				dummy = BO.v3
		if(42)
			for(var/i in 1 to reps)
				dummy = BO.v1490
	. = (world.tick_usage - t0) * world.tick_lag * 1e6 / reps
	if(id == 26 || id == 27)
		. *= 10
	dummy = dummy

/world/New()
	..()
	spawn(5)
		bench()

/proc/bench()
	case_names = list("baseline loop", "global proc, 0 args", "global proc, 1 arg", "datum proc, 0 args",
		"datum proc, 3 args", "datum proc, 3 named args", "datum proc, 3 default args unset", "datum proc, 10 locals",
		"datum proc, waitfor=FALSE", "5x ..() override chain", "proc on root, called on 20-deep type",
		"proc on type with 1500 procs", "var read, small datum", "var read, 1500-var type, default",
		"var read, 1500-var type, all overridden", "global var read", "GLOB.static read",
		"proc: a+a+a", "proc: x=a; x+x+x", "typed for over 100 (per item)", "as anything for over 100 (per item)",
		"L.len", "length(L)", "world.time", "world.tick_usage", "new small datum", "new datum with var/list = list()",
		"istype", "S.vars\\[\\"a\\"\\]", "proc a+a+a on 1500-override datum", "S.l && S.l\\[1\\] (null)", "src.a+src.b+src.c",
		"for x in list (plain, per item)", "for j in 1 to len (per item)", "S?.a", "isnull(S)", "S == null",
		"proc bp1400 on big", "proc bp3 on big", "var v3 on big default", "var v3 on big overridden", "var v1490 on big overridden")
	var/datum/small/S = new
	var/datum/big/B = new
	var/datum/big/BO = new
	BO.override_all()
	var/datum/small/C5 = new /datum/small/chain1/chain2/chain3/chain4/chain5
	var/datum/small/D20 = new /datum/small/d1/d2/d3/d4/d5/d6/d7/d8/d9/d10/d11/d12/d13/d14/d15/d16/d17/d18/d19/d20
	var/list/L100 = list()
	var/list/O100 = list()
	for(var/i in 1 to 100)
		L100 += new /datum/small
		O100 += i
	var/n = case_names.len
	var/list/samples = new/list(n)
	for(var/c in 1 to n)
		samples[c] = list()
	for(var/t in 1 to TRIES)
		for(var/c in 1 to n)
			sleep(world.tick_lag)
			samples[c] += run_case(c, REPS, S, B, BO, C5, D20, L100, O100)
	var/list/base = samples[1]
	var/base_min = min(base)
	world.log << "BASE loop ns per iter [round(base_min, 0.1)]"
	for(var/c in 1 to n)
		var/list/s = sortList(samples[c])
		var/mn = s[1] - base_min
		var/md = s[round((s.len + 1) / 2)] - base_min
		world.log << "RESULT | [case_names[c]] | [round(mn, 0.1)] | [round(md, 0.1)]"
	world.log << "DONE"
	shutdown()

/proc/sortList(list/L)
	var/list/r = L.Copy()
	for(var/i in 1 to r.len)
		for(var/j in i + 1 to r.len)
			if(r[j] < r[i])
				var/tmp = r[i]
				r[i] = r[j]
				r[j] = tmp
	return r
""")

with open(os.path.join(HERE, "micro.dm"), "w", newline="\n") as f:
    f.write("\n".join(out))
print("wrote micro.dm")
