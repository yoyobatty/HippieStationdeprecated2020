"""Generates varread.dm: does a var read cost less once the instance has written it (an override entry), with many cold objects?
And what does an override entry, an empty list, a datum cost in memory? Phases are printed to world.log with a pause after each
so run_varread.ps1 can read the process's private bytes at each one.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
NV = 300
out = []
w = out.append
w("""// GENERATED by gen_varread.py
#define N 100000
#define TRIES 7
/world
	fps = 10
	maxx = 10
	maxy = 10
	maxz = 1
	loop_checks = 0
""")
w("/datum/t300")
for i in range(NV):
    w(f"\tvar/v{i} = 0")
w("/datum/t300/var/list/lazy")
w("/datum/t300/var/list/eager")
w("""
/proc/us()
	return world.tick_usage * world.tick_lag * 1000

/proc/time_reads(list/objs, which)
	var/dummy
	var/t0 = world.tick_usage
	switch(which)
		if(1)
			for(var/datum/t300/o as anything in objs)
				dummy = o.v150
		if(2)
			for(var/datum/t300/o as anything in objs)
				dummy = o.v3
		if(3)
			for(var/datum/t300/o as anything in objs)
				dummy = o.v297
		if(4)
			for(var/datum/t300/o as anything in objs)
				dummy = o
	dummy = dummy
	return (world.tick_usage - t0) * world.tick_lag * 1e6 / objs.len

/proc/phase(name)
	world.log << "PHASE [name] [world.timeofday]"
	sleep(30)

/proc/report(label, list/objs)
	var/list/best = list(1e9, 1e9, 1e9, 1e9)
	for(var/t in 1 to TRIES)
		for(var/c in 1 to 4)
			sleep(1)
			best[c] = min(best[c], time_reads(objs, c))
	world.log << "READ | [label] | v150 [round(best[1] - best[4], 0.1)] | v3 [round(best[2] - best[4], 0.1)] | v297 [round(best[3] - best[4], 0.1)] ns (loop [round(best[4], 0.1)])"

/world/New()
	..()
	spawn(5)
		run_probe()

/proc/run_probe()
	phase("start")
	var/list/objs = new/list(N)
	for(var/i in 1 to N)
		objs[i] = new /datum/t300
	// scatter: interleave with garbage so neighbours in the list aren't neighbours in memory, then shuffle
	var/list/junk = list()
	for(var/i in 1 to N)
		junk += new /datum/t300
	for(var/i in N to 2 step -1)
		objs.Swap(i, rand(1, i))
	phase("made [N] datums x2")
	report("all default", objs)
	for(var/datum/t300/o as anything in objs)
		o.v150 = 0
		o.v3 = 0
		o.v297 = 0
	phase("wrote 3 vars (same value) on [N]")
	report("3 written", objs)
	for(var/datum/t300/o as anything in objs)
		for(var/i in 10 to 40)
			o.vars["v[i]"] = 1
	phase("wrote 31 more vars on [N]")
	report("34 written", objs)
	for(var/datum/t300/o as anything in objs)
		o.eager = list()
	phase("empty list on [N]")
	junk.Cut()
	phase("dropped [N] junk datums")
	world.log << "DONE"
	shutdown()
""")
open(os.path.join(HERE, "varread.dm"), "w", newline="\n").write("\n".join(out))
print("ok")
