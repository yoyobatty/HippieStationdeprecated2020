"""varread2.dm: read cost of one var against how many vars the instance has written (K), cold objects.
Populations of N datums each with K written vars, all created interleaved (so scattered), each list shuffled.
Also: write order (all at creation, versus spread out over time with other allocations between) for K=34.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
NV = 300
KS = [0, 1, 3, 8, 16, 34, 64, 128]
out = []
w = out.append
w("""// GENERATED by gen_varread2.py
#define N 40000
#define TRIES 7
/world
	fps = 10
	maxx = 10
	maxy = 10
	maxz = 1
	loop_checks = 0
""")
w("/datum/t300")
for i in range(NV):
    w(f"\tvar/v{i} = 0")
w("/datum/t300/proc/write_k(k)")
w("\tif(k >= 1)\n\t\tv150 = 1")
for i in range(1, 129):
    w(f"\tif(k > {i})\n\t\tv{(150 + i * 7) % NV} = 1")
w(f"var/list/ks = list({', '.join(map(str, KS))})")
w("""
/proc/time_reads(list/objs, which)
	var/dummy
	var/t0 = world.tick_usage
	if(which == 1)
		for(var/datum/t300/o as anything in objs)
			dummy = o.v150
	else
		for(var/datum/t300/o as anything in objs)
			dummy = o
	dummy = dummy
	return (world.tick_usage - t0) * world.tick_lag * 1e6 / objs.len

/world/New()
	..()
	spawn(5)
		run_probe()

/proc/shuffle_list(list/L)
	for(var/i in L.len to 2 step -1)
		L.Swap(i, rand(1, i))

/proc/run_probe()
	var/list/pops = list()
	for(var/k in ks)
		pops += list(list())
	var/list/late = list() // K=34, written later in rounds with other allocation between
	var/list/junk = list()
	for(var/i in 1 to N)
		for(var/p in 1 to ks.len)
			var/datum/t300/o = new
			o.write_k(ks[p])
			pops[p] += o
		var/datum/t300/l = new
		late += l
		junk += new /datum/t300
	for(var/round in 1 to 34)
		for(var/datum/t300/l as anything in late)
			l.write_k(round)
			junk += list(round)
	junk.Cut()
	for(var/list/L in pops)
		shuffle_list(L)
	shuffle_list(late)
	pops += list(late)
	var/list/names = list()
	for(var/k in ks)
		names += "K=[k]"
	names += "K=34 written over time"
	var/list/best = list()
	var/list/base = list()
	for(var/p in 1 to pops.len)
		best += 1e9
		base += 1e9
	for(var/t in 1 to TRIES)
		for(var/p in 1 to pops.len)
			sleep(1)
			best[p] = min(best[p], time_reads(pops[p], 1))
			sleep(1)
			base[p] = min(base[p], time_reads(pops[p], 2))
	for(var/p in 1 to pops.len)
		world.log << "READ | [names[p]] | [round(best[p] - base[p], 0.1)] ns"
	world.log << "DONE"
	shutdown()
""")
open(os.path.join(HERE, "varread2.dm"), "w", newline="\n").write("\n".join(out))
print("ok")
