for name, (accent, _bg, _title, _title_end, _label, body, _extra) in THEMES.items():
    t = oklab.dept_tokens(name)
    t['notice_alt'] = oklab.oklch(*_shift(t['notice'], -0.04))
    extra = EXTRA.get(name, '').format(**t)
    open(f'styles/themes/{name}.scss', 'w', newline='\n').write(SCSS.format(name=name, extra=extra, **t))
    # the emblem takes the theme's new accent, at about half its old strength
    open(f'assets/bg-{name}.svg', 'w', newline='\n').write(SVG.format(body=body.replace(accent, t['emblem'])))

wp = open('webpack.config.js', newline='').read()
anchor = "        path.resolve(__dirname, './styles/themes/clockwork.scss'),\n"
assert anchor in wp
for name in THEMES:
    line = f"        path.resolve(__dirname, './styles/themes/{name}.scss'),\n"
    if line not in wp:
        wp = wp.replace(anchor, anchor + line)
        anchor = line
open('webpack.config.js', 'w', newline='').write(wp)
