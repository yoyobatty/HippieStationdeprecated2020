def write_themes():
    for name, t in THEMES.items():
        v = dict(t, name=name)
        v['glow_clear'] = rgba(t['glow'], 0)
        v['rule_soft'] = rgba(t['rule'], 0.45)
        v['edge'] = rgba(t['rule'], 0.2)
        v['title_glow'] = rgba(t['title_end'], 0.45)
        v['head_glow'] = rgba(t['head'], 0.45)
        v['sel_glow'] = rgba(t['sel'], 0.5)
        v['sel_ink'] = ink(t['sel'])
        v['data_glow'] = rgba(t['data'], 0.55)
        v['scroll'] = rgba(t['rule'], 0.35)
        v['disabled'] = f"    'color-disabled': {t['disabled']},\n" if t['disabled'] else ''
        v['emblem_rule'] = (f"  .Layout__content {{\n    background-image: {t['emblem']};\n  }}\n" if t['emblem'] else '')
        v['extra'] = EXTRA.get(name, '').format(cog=rgba(t['rule'], 0.07))
        path = os.path.join(TGUI, 'styles', 'themes', name + '.scss')
        nl = '\r\n' if '\r\n' in open(path, encoding='utf-8', newline='').read() else '\n'
        open(path, 'w', encoding='utf-8', newline=nl).write(SCSS.format(**v))
        print('wrote', path)


def boost_mech_paints():
    """Text, dim and bar colours of each paint to the most vivid sRGB colour at their OKLab lightness and hue.
    Paints that are meant to be pale or grey (chroma under 0.05: the Marauder, the mime) stay as they are."""
    path = os.path.join(TGUI, 'interfaces', 'Exosuit.js')
    src = open(path, encoding='utf-8', newline='').read()
    a = src.index('const PAINTS = {')
    b = src.index('};', a)
    block = src[a:b]

    def paint(m):
        colours = re.findall(r"'(#[0-9a-fA-F]{6})'", m.group(0))
        out = m.group(0)
        for i in (0, 1, 2):
            L, C, H = hex_to_oklch(colours[i])
            if C < 0.05:
                continue
            new = vivid(L, H)
            out = out.replace(f"'{colours[i]}'", f"'{new}'", 1)
        return out
    block2 = re.sub(r"\w+: \[[^\]]*\]", paint, block)
    open(path, 'w', encoding='utf-8', newline='').write(src[:a] + block2 + src[b:])
    print('boosted mech paints in', path)


if __name__ == '__main__':
    write_themes()
    boost_mech_paints()
